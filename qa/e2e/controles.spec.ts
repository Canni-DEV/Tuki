import { expect, type Page } from '@playwright/test'
import { test } from './reloj-partida'

const estado = (page: Page) => page.evaluate(() => window.tukiQA.estado())
const punto = (page: Page, posicion: number[]) => page.evaluate(p => window.tukiQA.proyectar(p), posicion)
async function cargar(page: Page, nombre = 'recta') {
  await page.goto('./?revision')
  await page.evaluate(n => window.tukiQA.cargar(n), nombre)
  await expect(page.getByRole('button', { name: 'Empujar', exact: true })).toBeEnabled()
}

test('Espacio empuja, recupera el armado y avanza una sola vez por pulsación', async ({ page, pausarPartida }) => {
  await cargar(page)
  await page.getByRole('button', { name: 'Vista superior' }).click()
  const centro = await punto(page, [0, 0, 0])
  await page.mouse.click(centro.x, centro.y)
  const antes = await estado(page)
  await pausarPartida()
  await page.keyboard.down('Space')
  await page.clock.runFor(64)
  await page.keyboard.down('Space')
  expect((await estado(page)).fase).toBe('prueba')
  await page.keyboard.up('Space')
  await page.keyboard.press('Space')
  expect(await estado(page)).toMatchObject({ fase: 'edicion', armado: antes.armado, seleccion: antes.seleccion, historia: antes.historia })

  await page.keyboard.down('Space')
  await page.clock.runFor(12000)
  await expect(page.getByRole('heading', { name: 'Completaste La recta' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Volver a editar', exact: true })).toBeVisible()
  await page.keyboard.down('Space')
  expect((await estado(page)).armado.nivel).toBe('recta')
  await page.keyboard.up('Space')
  await page.clock.resume()
  await page.keyboard.press('Space')
  await expect(page.getByRole('heading', { name: '02 · La curva' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Empujar', exact: true })).toBeEnabled()
  await page.keyboard.press('Space')
  await expect(page.getByRole('heading', { name: 'Cadena detenida' })).toBeVisible()
  await page.keyboard.press('Space')
  expect((await estado(page)).fase).toBe('edicion')
})

for (const fixture of ['bajada', 'llave-abierta']) {
  test('Espacio vuelve a editar al ganar ' + fixture, async ({ page, pausarPartida }) => {
    await cargar(page, fixture)
    const antes = await estado(page)
    await pausarPartida()
    await page.keyboard.press('Space')
    await page.clock.runFor(30000)
    await expect(page.getByRole('heading', { name: /^Completaste / })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Volver a editar', exact: true })).toHaveAttribute('aria-keyshortcuts', 'Space')
    await page.keyboard.press('Space')
    expect(await estado(page)).toMatchObject({ fase: 'edicion', armado: antes.armado })
  })
}

test('la rueda conserva números, recibe teclado y consume el clic exterior', async ({ page }, testInfo) => {
  await cargar(page, 'taza-fichas')
  const banda = page.locator('#bandeja .pieces')
  const tipos = await banda.locator('[data-tool]').evaluateAll(bs => bs.map(b => (b as HTMLElement).dataset.tool))
  expect(tipos).toEqual(['domino', 'bolita', 'taco', 'cuna', 'rampa', 'canal', 'embudo'])
  await expect(banda.locator('[data-tool=domino]')).toBeDisabled()
  await expect(banda.locator('[data-tool=domino] kbd')).toHaveText('1')
  await page.mouse.move(1300, 20)
  await page.keyboard.press('t')
  const menu = page.getByRole('dialog', { name: 'Piezas disponibles' })
  await expect(menu).toHaveClass(/radial-menu/)
  await expect(menu).toBeInViewport({ ratio: 1 })
  await page.screenshot({ path: testInfo.outputPath('inventario-circular.png') })
  await page.keyboard.press('Digit1')
  await expect(menu).toBeVisible()
  await page.keyboard.press('End')
  await expect(menu.getByRole('button', { name: 'Cerrar inventario' })).toBeFocused()
  await page.keyboard.press('Home')
  await expect(menu.locator('[data-tool=bolita]')).toBeFocused()
  await page.keyboard.press('Numpad2')
  await expect(menu).toHaveCount(0)
  await expect(banda.locator('[data-tool=bolita]')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#mesa')).toBeFocused()
  const antes = await estado(page)
  await page.keyboard.press('t')
  await page.mouse.click(30, 200)
  await expect(menu).toHaveCount(0)
  expect((await estado(page)).armado).toEqual(antes.armado)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Piezas', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(menu).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Piezas', exact: true })).toBeFocused()
  expect((await estado(page)).fase).toBe('edicion')
  await page.evaluate(() => window.tukiQA.cargar('puente'))
  await page.mouse.move(600, 350)
  await page.keyboard.press('t')
  await expect(menu.locator('[data-tool]')).toHaveCount(9)
  await page.screenshot({ path: testInfo.outputPath('inventario-nueve-piezas.png') })
  await expect(menu.locator('[data-tool=canal]')).toBeEnabled()
  const ficha = await menu.locator('[data-tool=canal] .piece-content').boundingBox()
  await page.mouse.move(ficha!.x + ficha!.width / 2, ficha!.y + ficha!.height / 2)
  expect(await menu.locator('[data-tool=canal]').evaluate(el => el.matches(':hover'))).toBe(true)
  await page.mouse.click(ficha!.x + ficha!.width / 2, ficha!.y + ficha!.height / 2)
  await expect(menu).toHaveCount(0)
  await expect(page.locator('#bandeja [data-tool=canal]')).toHaveAttribute('aria-pressed', 'true')
})

