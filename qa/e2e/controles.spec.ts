test('números colocan una unidad y las flechas ajustan según la cámara con deshacer', async ({ page }, testInfo) => {
  await cargar(page)
  await page.getByRole('button', { name: 'Vista superior' }).click()
  await page.keyboard.press('f')
  await expect(page.getByRole('button', { name: 'Trazar fila' })).toHaveClass(/active/)
  await page.keyboard.press('f')
  await expect(page.getByRole('button', { name: 'Trazar fila' })).not.toHaveClass(/active/)
  await page.keyboard.press('Digit1')
  const pos = await punto(page, [0, 0, .05])
  await page.mouse.click(pos.x, pos.y)
  let antes = await estado(page)
  const id = antes.seleccion!
  const colocada = antes.armado.piezas.find(p => p.id === id)!
  const pieza = () => estado(page).then(s => s.armado.piezas.find(p => p.id === id)!)
  expect(antes.armado.piezas).toHaveLength(6)
  await expect(page.locator('#bandeja [data-tool=domino]')).toBeDisabled()
  await page.keyboard.press('Numpad1')
  expect((await estado(page)).armado).toEqual(antes.armado)
  await page.keyboard.press('ArrowRight')
  expect((await pieza()).posicion[0]).toBeCloseTo(colocada.posicion[0] + .002, 7)
  await page.keyboard.press('Shift+ArrowUp')
  expect((await pieza()).posicion[2]).toBeCloseTo(colocada.posicion[2] - .0005, 7)
  await page.keyboard.press('q')
  expect((await pieza()).giroY).toBe(75)
  await page.keyboard.press('Shift+e')
  expect((await pieza()).giroY).toBe(76)
  for (let i = 0; i < 4; i++) await page.keyboard.press('Control+z')
  expect((await estado(page)).armado).toEqual(antes.armado)
  await page.getByRole('button', { name: 'Ver mesa', exact: true }).click()
  await page.mouse.move(650, 330)
  await page.mouse.down({ button: 'right' })
  await page.mouse.move(850, 350, { steps: 8 })
  await page.mouse.up({ button: 'right' })
  const inicial = (await pieza()).posicion
  const pantalla = await punto(page, inicial)
  await page.keyboard.press('ArrowRight')
  const final = (await pieza()).posicion
  expect(Math.hypot(final[0] - inicial[0], final[2] - inicial[2])).toBeCloseTo(.002, 7)
  const desplazado = await punto(page, final)
  expect(desplazado.x).toBeGreaterThan(pantalla.x)
  expect(desplazado.y).toBeCloseTo(pantalla.y, 4)
  await page.getByRole('button', { name: 'Ajustar', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('ajuste-fino.png') })
  await page.getByRole('button', { name: 'Fino', exact: true }).click()
  antes = await estado(page)
  await page.getByRole('button', { name: 'Mover arriba', exact: true }).click()
  expect((await estado(page)).historia).toBe(antes.historia + 1)
  await page.locator('#mesa').focus()
  await page.keyboard.press('Delete')
  expect((await estado(page)).armado.piezas.some(p => p.id === id)).toBe(false)
  await page.keyboard.press('Control+z')
  expect((await estado(page)).armado.piezas.some(p => p.id === id)).toBe(true)
  await page.getByRole('button', { name: 'Preferencias' }).click()
  const congelado = await estado(page)
  await page.keyboard.press('Space')
  await page.keyboard.press('f')
  await page.keyboard.press('ArrowRight')
  expect(await estado(page)).toMatchObject({ fase: congelado.fase, armado: congelado.armado, historia: congelado.historia })
})

test('el movimiento rechazado y los atajos durante un arrastre conservan el armado', async ({ page }) => {
  await cargar(page)
  await page.getByRole('button', { name: 'Vista superior' }).click()
  const centro = await punto(page, [0, 0, 0])
  await page.mouse.click(centro.x, centro.y)
  for (let i = 0; i < 15; i++) await page.keyboard.press('ArrowRight')
  const limite = await estado(page)
  await page.keyboard.press('ArrowRight')
  expect(await estado(page)).toMatchObject({ armado: limite.armado, historia: limite.historia })
  await expect(page.getByRole('status').filter({ hasText: 'Separá las piezas' })).toBeVisible()
  const seleccionada = limite.armado.piezas.find(p => p.id === limite.seleccion)!
  const origen = await punto(page, seleccionada.posicion)
  await page.mouse.move(origen.x, origen.y)
  await page.mouse.down()
  await page.mouse.move(origen.x, origen.y + 35)
  for (const key of ['t', 'Digit1', 'f', 'Space', 'Delete']) await page.keyboard.press(key)
  await expect(page.getByRole('dialog', { name: 'Piezas disponibles' })).toHaveCount(0)
  expect((await estado(page)).fase).toBe('edicion')
  await page.keyboard.press('Escape')
  await page.mouse.up()
  expect((await estado(page)).armado).toEqual(limite.armado)
})

test('volver a editar recupera la cámara previa y conserva el historial utilizable', async ({ page, pausarPartida }) => {
  await cargar(page)
  await page.getByRole('button', { name: 'Vista superior' }).click()
  const centro = await punto(page, [0, 0, 0])
  await page.mouse.click(centro.x, centro.y)
  const original = await estado(page)
  await page.keyboard.press('Shift+ArrowUp')
  const antes = await estado(page)
  const vista = () => page.evaluate(() => (window.tukiQA.estado() as unknown as { vista: unknown }).vista)
  const vistaAntes = await vista()
  await pausarPartida()
  await page.keyboard.press('Space')
  await page.mouse.move(650, 300)
  await page.mouse.down({ button: 'right' })
  await page.mouse.move(780, 340, { steps: 5 })
  await page.mouse.up({ button: 'right' })
  expect(await vista()).not.toEqual(vistaAntes)
  await page.keyboard.press('Space')
  expect(await estado(page)).toMatchObject({ fase: 'edicion', armado: antes.armado, historia: antes.historia, seleccion: antes.seleccion })
  expect(await vista()).toEqual(vistaAntes)
  await page.keyboard.press('Control+z')
  expect((await estado(page)).armado).toEqual(original.armado)
})

test('el ajuste fino mantiene la altura y valida el borde de un apoyo elevado', async ({ page }) => {
  await cargar(page, 'bajada')
  await page.getByRole('button', { name: 'Más acciones', exact: true }).click()
  await page.getByRole('button', { name: 'Retirar todas', exact: true }).click()
  await page.getByRole('button', { name: 'Vista superior' }).click()
  await page.locator('#bandeja [data-tool=taco]').click()
  const centro = await punto(page, [-.161, .175, -.235])
  await page.mouse.click(centro.x, centro.y)
  const antes = await estado(page)
  const id = antes.seleccion!
  const pieza = () => estado(page).then(s => s.armado.piezas.find(p => p.id === id)!)
  const original = await pieza()
  expect(original.apoyo).toBe('cima-tapa')
  expect(original.posicion[1]).toBeCloseTo(.175, 7)
  await page.keyboard.press('Shift+ArrowRight')
  expect((await pieza()).posicion[0]).toBeCloseTo(original.posicion[0] + .0005, 7)
  expect((await pieza()).posicion[1]).toBe(original.posicion[1])
  await page.keyboard.press('Control+z')
  expect((await estado(page)).armado).toEqual(antes.armado)
  // Walk to the edge: the first rejected step must preserve the last accepted pose and undo count.
  for (let paso = 0; paso < 40; paso++) {
    const anterior = await estado(page)
    await page.keyboard.press('ArrowLeft')
    const actual = await estado(page)
    expect((await pieza()).posicion[1]).toBe(original.posicion[1])
    if (actual.historia === anterior.historia) {
      expect(actual.armado).toEqual(anterior.armado)
      await expect(page.locator('#aviso')).toHaveClass(/visible/)
      return
    }
  }
  throw new Error('No se alcanzó el borde del apoyo')
})
