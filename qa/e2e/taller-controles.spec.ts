async function iniciar(page: Page) {
  await page.addInitScript(completados => {
    if (!localStorage.getItem('tuki.v1.preferencias.audio')) window.tukiPrueba.sembrar({
      completados, audio: false, movimiento: 'reducido',
    })
  }, idsNiveles.filter(id => id !== 'taller'))
  await page.goto('./?revision')
  await page.getByRole('button', { name: 'Taller libre', exact: true }).click()
}
async function nueva(page: Page) {
  await iniciar(page)
  await page.getByRole('button', { name: 'Nueva mesa', exact: true }).click()
  await page.getByLabel('Nombre de la mesa').fill('Mesa de controles')
  await page.getByRole('button', { name: 'Crear mesa', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Piezas', exact: true })).toBeEnabled()
}
async function estado(page: Page) {
  await expect.poll(() => page.evaluate(() => window.tukiQA.estado().validando)).toBe(false)
  return page.evaluate(() => window.tukiQA.estado())
}
async function tocar(page: Page, posicion: number[]) {
  const p = await page.evaluate(pos => window.tukiQA.proyectar(pos), posicion)
  await page.mouse.click(p.x, p.y)
  return estado(page)
}
const menu = (page: Page) => page.getByRole('dialog', { name: 'Piezas disponibles', exact: true })

