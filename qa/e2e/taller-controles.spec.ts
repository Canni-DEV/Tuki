test.describe('taller táctil', () => {
  test.use({ viewport: { width: 390, height: 844 }, hasTouch: true })
  test('el catálogo y Ajustar caben en vertical, horizontal y 320 px', async ({ page, browserName }, info) => {
    test.skip(browserName === 'firefox' && info.project.use.channel === 'moz-firefox', 'Firefox BiDi de escritorio no implementa tap.')
    await nueva(page)
    for (const [width, height] of [[390, 844], [844, 390], [320, 640]]) {
      await page.setViewportSize({ width, height })
      await page.getByRole('button', { name: 'Piezas', exact: true }).tap()
      await expect(menu(page)).toBeInViewport({ ratio: 1 })
      await expect(menu(page).locator('[data-tool]')).toHaveCount(45)
      await page.getByLabel('Categoría', { exact: true }).selectOption('Libros')
      await menu(page).locator('[data-tool=atlasGrande]').scrollIntoViewIfNeeded()
      // Fractional grid widths can leave a subpixel at the scroll boundary.
      await expect(menu(page).locator('[data-tool=atlasGrande]')).toBeInViewport({ ratio: .99 })
      await page.screenshot({ path: info.outputPath(`catalogo-taller-${width}.png`) })
      await page.getByRole('button', { name: 'Cerrar inventario' }).tap()
      await page.getByRole('button', { name: 'Piezas', exact: true }).tap()
      await page.getByLabel('Categoría', { exact: true }).selectOption('')
      await page.getByRole('button', { name: 'Cerrar inventario' }).tap()
    }
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: 'Piezas', exact: true }).tap()
    await page.getByRole('searchbox', { name: 'Buscar piezas' }).fill('atlas')
    // Desktop touch emulation has no OS keyboard; simulate its visual viewport
    // while leaving the layout viewport tall, as a mobile browser does.
    await page.evaluate(() => {
      Object.defineProperty(window.visualViewport!, 'height', { configurable: true, value: 320 })
      window.visualViewport!.dispatchEvent(new Event('resize'))
    })
    await expect(menu(page)).toHaveClass(/compact-catalog/)
    expect(await menu(page).evaluate(el => el.getBoundingClientRect().bottom)).toBeLessThanOrEqual(320)
    await expect(menu(page).locator('[data-tool=atlas]')).toBeInViewport({ ratio: .99 })
    await page.evaluate(() => {
      Reflect.deleteProperty(window.visualViewport!, 'height')
      window.visualViewport!.dispatchEvent(new Event('resize'))
    })
    await page.getByRole('button', { name: 'Cerrar inventario' }).tap()
    await page.getByRole('button', { name: 'Vista superior' }).tap()
    await page.locator('#bandeja [data-tool=domino]').tap()
    const pos = await page.evaluate(() => window.tukiQA.proyectar([0, 0, 0]))
    await page.touchscreen.tap(pos.x, pos.y)
    const colocada = (await estado(page)).armado.piezas[0] as unknown as PiezaColocada
    await page.getByRole('button', { name: 'Ajustar', exact: true }).tap()
    await expect(page.getByRole('group', { name: 'Ajuste fino' })).toBeInViewport({ ratio: 1 })
    await page.getByRole('button', { name: 'Fino', exact: true }).tap()
    await page.getByRole('button', { name: 'Mover arriba', exact: true }).tap()
    const pieza = (await estado(page)).armado.piezas[0] as unknown as PiezaColocada
    expect(pieza.posicion[2]-colocada.posicion[2]).toBeCloseTo(-.0005, 6)
    await page.screenshot({ path: info.outputPath('ajuste-taller-tactil.png') })
  })
})
