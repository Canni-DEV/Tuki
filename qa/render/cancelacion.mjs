import { chromium } from 'playwright'
import { writeFile } from 'node:fs/promises'
const browser=await chromium.launch({executablePath:process.env.TUKI_CHROME??'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true,ignoreDefaultArgs:['--enable-unsafe-swiftshader']})
const report={errors:[]}
try {
  const page=await browser.newPage({viewport:{width:1366,height:768}})
  page.on('pageerror',e=>report.errors.push(e.message))
  await page.addInitScript(()=>{localStorage.setItem('tuki.v1.preferencias.audio','false');localStorage.setItem('tuki.v1.preferencias.movimiento','"reducido"')})
  await page.goto(process.env.TUKI_BASE_URL??'http://127.0.0.1:4176/?revision');await page.waitForFunction(()=>!!window.tukiQA)
  await page.evaluate(()=>window.tukiQA.cargar('vuelta'))
  const before=await page.evaluate(()=>window.tukiQA.estado())
  await page.route('**/fotorealista/recursos/**',async route=>{await new Promise(r=>setTimeout(r,2000));await route.continue().catch(()=>{})})
  const request=page.waitForRequest(r=>r.url().includes('/fotorealista/recursos/'))
  await page.getByRole('button',{name:'Preferencias',exact:true}).click();await page.getByLabel('Visuales',{exact:true}).selectOption('fotorealista');await request
  await page.getByRole('button',{name:'Cerrar',exact:true}).click();await page.keyboard.press('Space')
  if((await page.evaluate(()=>window.tukiQA.estado())).fase!==before.fase)throw new Error('Se pudo empujar durante la comprobación')
  await page.getByRole('button',{name:'Cancelar preparación visual',exact:true}).click()
  await page.waitForFunction(()=>!window.tukiQA.render.fotorealista().busy)
  await page.unrouteAll({behavior:'wait'})
  report.cancelled=await page.evaluate(()=>window.tukiQA.render.fotorealista())
  await page.getByRole('button',{name:'Preferencias',exact:true}).click();await page.getByLabel('Visuales',{exact:true}).selectOption('fotorealista')
  await page.waitForFunction(()=>window.tukiQA.render.fotorealista()?.message.includes('Comprobando luz'))
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{value:true,configurable:true});document.dispatchEvent(new Event('visibilitychange'))})
  await page.waitForFunction(()=>!window.tukiQA.render.fotorealista().busy)
  report.hidden=await page.evaluate(()=>window.tukiQA.render.fotorealista())
  if(!report.hidden.message.includes('Volvé a la pestaña'))throw new Error('No se canceló al ocultar la pestaña')
  await page.evaluate(()=>{delete document.hidden;document.dispatchEvent(new Event('visibilitychange'))})
  await page.route('**/fotorealista/recursos/*-madera-color.png',route=>route.fulfill({status:503,body:''}))
  await page.getByLabel('Visuales',{exact:true}).selectOption('fotorealista');await page.waitForFunction(()=>!window.tukiQA.render.fotorealista().busy)
  report.network=await page.evaluate(()=>window.tukiQA.render.fotorealista())
  if(report.network.active||!report.network.message.includes('Se activó Default'))throw new Error('No se recuperó de la carga fallida')
  await page.unrouteAll();await page.getByLabel('Visuales',{exact:true}).selectOption('fotorealista')
  await page.waitForFunction(()=>window.tukiQA.render.fotorealista().active,null,{timeout:120000})
  report.recovered=await page.evaluate(()=>window.tukiQA.render.fotorealista())
  const after=await page.evaluate(()=>window.tukiQA.estado())
  for(const key of ['armado','seleccion','vista','fase'])if(JSON.stringify(before[key])!==JSON.stringify(after[key]))throw new Error('Cambió '+key)
  if(report.errors.length)throw new Error(report.errors.join('\n'))
  console.log('Cancelación, pestaña oculta, fallo de red y reintento: OK')
}finally{await browser.close();await writeFile('.qa-local/fotorealista/cancelacion.json',JSON.stringify(report,null,2))}
