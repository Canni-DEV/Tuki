import { chromium } from 'playwright'
import { mkdir,writeFile } from 'node:fs/promises'
const folder='.qa-local/fotorealista';await mkdir(folder,{recursive:true})
const browser=await chromium.launch({executablePath:process.env.TUKI_CHROME??'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true,ignoreDefaultArgs:['--enable-unsafe-swiftshader']})
try {
  const context=await browser.newContext({viewport:{width:2560,height:1440}}),page=await context.newPage(),errors=[]
  page.on('pageerror',e=>{errors.push(e.message);console.log(e.message)})
  page.on('console',m=>{if(m.type()==='error'){errors.push(m.text());console.log(m.text().slice(0,500))}})
  await page.addInitScript(()=>{localStorage.setItem('tuki.v1.preferencias.audio','false');localStorage.setItem('tuki.v1.preferencias.movimiento','"completo"')})
  await page.goto(process.env.TUKI_BASE_URL??'http://127.0.0.1:4176/?revision');await page.waitForFunction(()=>!!window.tukiQA)
  await page.evaluate(()=>window.tukiQA.cargar('vuelta'))
  const before=await page.evaluate(()=>window.tukiQA.estado())
  await page.getByRole('button',{name:'Preferencias',exact:true}).click()
  await page.screenshot({path:`${folder}/configuracion.png`})
  await page.getByLabel('Visuales',{exact:true}).selectOption('fotorealista')
  await page.waitForFunction(()=>{const s=window.tukiQA.render.fotorealista();return s&&!s.busy&&(s.active||s.message)},null,{timeout:120000})
  const state=await page.evaluate(()=>window.tukiQA.render.fotorealista());console.log(JSON.stringify(state))
  await page.getByRole('button',{name:'Cerrar',exact:true}).click()
  await page.screenshot({path:`${folder}/activado.png`})
  const after=await page.evaluate(()=>window.tukiQA.estado())
  if(!state.active)throw new Error('Fotorealista no se activó: '+state.message)
  await page.waitForFunction(()=>window.tukiQA.render.fotorealista().thumbnails>=6)
  for(const field of ['armado','vista','seleccion','fase'])if(JSON.stringify(before[field])!==JSON.stringify(after[field]))throw new Error('Cambió '+field)
  await page.getByRole('button',{name:'Empujar',exact:true}).click()
  await page.waitForFunction(()=>window.tukiQA.estado().fase==='resultado',null,{timeout:45000})
  const result=await page.evaluate(()=>window.tukiQA.estado());if(result.resultado!=='victoria')throw new Error('La partida no ganó')
  await page.screenshot({path:`${folder}/victoria.png`})
  await page.getByRole('button',{name:'Preferencias',exact:true}).click();await page.getByLabel('Visuales',{exact:true}).selectOption('actual')
  await page.getByRole('button',{name:'Cerrar',exact:true}).click()
  const restored=await page.evaluate(()=>window.tukiQA.estado());if(restored.resultado!==result.resultado)throw new Error('Se perdió el resultado')
  await writeFile(`${folder}/activacion.json`,JSON.stringify({state,before,after,result,restored,errors},null,2))
  if(errors.length)throw new Error(errors.join('\n'))
  console.log('Activación, estado preservado, jugada ganadora y retorno a Actual: OK')
} finally {await browser.close()}
